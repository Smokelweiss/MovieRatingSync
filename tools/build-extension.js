/**
 * Build `extension/content.js` from the userscript.
 *
 * `movie-rating-sync.user.js` is the single source of truth. This script:
 *   1. strips the `==UserScript==` header,
 *   2. prepends a `GM_*` shim backed by `window.__mrsExtHook`, which
 *      `extension/content-bootstrap.js` installs in the same isolated world,
 *   3. writes `extension/content.js` and syncs the manifest versions.
 *
 * Re-run after every userscript change:  node tools/build-extension.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'movie-rating-sync.user.js');
const OUT_DIR = path.join(ROOT, 'extension');
const OUT = path.join(OUT_DIR, 'content.js');

// The engine resolves `GM_getValue` etc. as globals, exactly like a userscript
// manager's sandbox. Assigning them to `window` gives that same lexical lookup.
const GM_SHIM = `// --- Extension shim (generated by tools/build-extension.js) -----------------
// content-bootstrap.js installs window.__mrsExtHook before this file runs.
(function () {
    'use strict';
    var hook = window.__mrsExtHook;
    if (!hook) {
        // Fail loudly: without the bridge every network call would silently
        // return null and an import would look like "nothing was found".
        throw new Error('[mrs] extension bridge missing: content-bootstrap.js did not run');
    }
    window.GM_getValue = function (key, def) {
        var value = hook.readValue(key);
        return value === undefined ? def : value;
    };
    window.GM_setValue = function (key, value) { hook.setValue(key, value); };
    window.GM_deleteValue = function (key) { hook.deleteValue(key); };
    window.GM_addStyle = function (css) {
        var style = document.createElement('style');
        style.textContent = css;
        (document.head || document.documentElement).appendChild(style);
        return style;
    };

    // A request to the page's own origin is issued by the content script itself.
    // The browser then attaches the session cookies and generates Origin/Referer,
    // which the write endpoints (Letterboxd rate / watch / like) validate. The
    // background proxy runs in the extension origin, so fetch there strips those
    // headers and the site would answer 403 instead of saving the rating.
    function isSameOrigin(url) {
        try { return new URL(url, location.href).origin === location.origin; }
        catch (e) { return false; }
    }

    function headersToRaw(h) {
        var out = '';
        var CRLF = String.fromCharCode(13) + String.fromCharCode(10);
        if (h && typeof h.forEach === 'function') {
            h.forEach(function (value, key) { out += key + ': ' + value + CRLF; });
        }
        return out;
    }

    function viaPage(details, deliver) {
        var timeout = Number(details.timeout) > 0 ? Number(details.timeout) : 15000;
        var ctrl = typeof AbortController === 'function' ? new AbortController() : null;
        var settled = false;
        var finish = function (res) {
            if (settled) return;
            settled = true;
            clearTimeout(tid);
            deliver(res);
        };
        var tid = setTimeout(function () {
            if (ctrl) { try { ctrl.abort(); } catch (e) { /* ignore */ } }
            finish({ status: 0, statusText: '', responseHeaders: '', responseText: '', error: 'Timeout after ' + timeout + 'ms' });
        }, timeout);
        var method = details.method || 'GET';
        var init = {
            method: method,
            credentials: 'same-origin',
            headers: details.headers || {},
        };
        if (details.data != null && method !== 'GET' && method !== 'HEAD') init.body = details.data;
        if (ctrl) init.signal = ctrl.signal;
        fetch(details.url, init).then(function (r) {
            return r.text().then(function (text) { return { r: r, text: text }; });
        }).then(function (out) {
            finish({
                status: out.r.status,
                statusText: out.r.statusText || '',
                responseHeaders: headersToRaw(out.r.headers),
                responseText: out.text,
                finalUrl: out.r.url,
            });
        }, function (e) {
            finish({ status: 0, statusText: '', responseHeaders: '', responseText: '', error: String((e && e.message) || e) });
        });
    }

    function deliver(details) {
        return function (r) {
            var res = {
                status: r.status,
                statusText: r.statusText,
                responseHeaders: r.responseHeaders,
                responseText: r.responseText,
                finalUrl: r.finalUrl,
            };
            if (r.error && !(r.status > 0)) {
                res.error = r.error;
                if (typeof details.onerror === 'function') details.onerror(res);
            } else if (typeof details.onload === 'function') {
                details.onload(res);
            }
        };
    }

    window.GM = {
        xmlHttpRequest: function (details) {
            if (isSameOrigin(details.url)) {
                viaPage(details, deliver(details));
                return;
            }
            hook.request(details).then(deliver(details), function (e) {
                if (typeof details.onerror === 'function') {
                    details.onerror({ status: 0, statusText: '', responseHeaders: '', responseText: '', error: String((e && e.message) || e) });
                }
            });
        },
    };
})();
`;

function readHeader(src) {
    const match = src.match(/^\uFEFF?\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==[ \t]*\r?\n/);
    if (!match) throw new Error('userscript header not found in ' + SRC);
    return match;
}

function main() {
    const src = fs.readFileSync(SRC, 'utf8');
    const match = readHeader(src);
    const version = (match[0].match(/\/\/\s*@version\s+(\S+)/) || [])[1];
    if (!version) throw new Error('@version not found in userscript header');
    const body = src.slice(match[0].length);
    // Keep one line-ending style in the artifact: match the userscript's own.
    const eol = src.includes('\r\n') ? '\r\n' : '\n';
    const out = ('/* Generated by tools/build-extension.js - edit movie-rating-sync.user.js instead */\n'
        + GM_SHIM + body.trimEnd() + '\n').replace(/\r?\n/g, eol);
    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(OUT, out, 'utf8');
    syncManifestVersions(version);
    console.log('wrote', path.relative(ROOT, OUT), out.length, 'chars, version', version);
}

// Manifests must carry the same version as the userscript, otherwise the
// browser reports a different update version than the script header.
function syncManifestVersions(version) {
    for (const name of ['manifest.json', 'manifest.firefox.json']) {
        const file = path.join(OUT_DIR, name);
        if (!fs.existsSync(file)) continue;
        const raw = fs.readFileSync(file, 'utf8');
        const next = raw.replace(/("version"\s*:\s*")[^"]*(")/, `$1${version}$2`);
        if (next !== raw) {
            fs.writeFileSync(file, next, 'utf8');
            console.log('manifest version ->', version, 'in', name);
        }
    }
}

main();
