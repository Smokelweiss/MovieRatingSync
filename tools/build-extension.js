/**
 * Build the browser-extension content script from the userscript.
 *
 * `movie-rating-sync.user.js` is the single source of truth. This script:
 *   1. strips the `==UserScript==` header,
 *   2. appends a small shim that maps the GM_* / GM.* APIs onto
 *      `window.__mrsExtHook` (the bridge installed by content-bootstrap.js),
 *   3. writes `extension/content.js`.
 *
 * Re-run after every userscript change:  node tools/build-extension.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'movie-rating-sync.user.js');
const OUT_DIR = path.join(ROOT, 'extension');
const OUT = path.join(OUT_DIR, 'content.js');

const GM_SHIM = `
// --- Extension shim (generated by tools/build-extension.js) -----------------
// The engine above was written for userscript managers. In the extension it is
// injected into the page, so GM_* APIs are backed by window.__mrsExtHook,
// which content-bootstrap.js serves over postMessage from the content-script
// world. Requests are proxied by extension/background.js.
(function () {
    const hook = window.__mrsExtHook;
    if (!hook) {
        console.error('[mrs] extension bridge missing: content-bootstrap.js did not run');
        return;
    }
    // Function declarations create bindings the engine's 'use strict' IIFE can
    // resolve lexically, exactly like a userscript manager's sandbox.
    function GM_getValue(key, def) { return hook.getValue(key, def); }
    function GM_setValue(key, value) { void hook.setValue(key, value); }
    function GM_deleteValue(key) { void hook.deleteValue(key); }
    function GM_addStyle(css) {
        const style = document.createElement('style');
        style.textContent = css;
        (document.head || document.documentElement).appendChild(style);
        return style;
    }
    var GM = { xmlHttpRequest: (details) => { void hook.request(details); } };
    // Expose for debugging from the page console; the engine never needs this.
    window.MRS_GM = { GM, GM_getValue, GM_setValue, GM_deleteValue, GM_addStyle };
})();
`;

function main() {
    const src = fs.readFileSync(SRC, 'utf8');
    const match = src.match(/^\uFEFF?\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==[ \t]*\r?\n/);
    if (!match) throw new Error('userscript header not found in ' + SRC);
    const version = (match[0].match(/\/\/\s*@version\s+(\S+)/) || [])[1];
    if (!version) throw new Error('@version not found in userscript header');
    const body = src.slice(match[0].length);
    // Keep one line-ending style in the artifact: match the userscript's own.
    const eol = src.includes('\r\n') ? '\r\n' : '\n';
    const out = ('/* Generated by tools/build-extension.js - edit movie-rating-sync.user.js instead */\n'
        + body.trimEnd() + '\n' + GM_SHIM).replace(/\r?\n/g, eol);
    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(OUT, out, 'utf8');
    syncManifestVersions(version);
    console.log('wrote', path.relative(ROOT, OUT), out.length, 'chars');
}

// Manifests must carry the same version as the userscript, otherwise
// browsers report a different update version than the script header.
function syncManifestVersions(version) {
    for (const name of ['manifest.json', 'manifest.firefox.json']) {
        const file = path.join(OUT_DIR, name);
        if (!fs.existsSync(file)) continue;
        const raw = fs.readFileSync(file, 'utf8');
        const next = raw.replace(/("version"\s*:\s*")[^"]*(")/, `$1${version}$2`);
        if (next !== raw) {
            fs.writeFileSync(file, next, 'utf8');
            console.log('manifest version ->', version, 'in', name);
        }
    }
}

main();
