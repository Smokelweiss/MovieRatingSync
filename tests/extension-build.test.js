'use strict';

/**
 * Extension build tests.
 * Run: node tests/extension-build.test.js
 *
 * The extension is generated from the userscript, so the artifact must always
 * agree with the script it was generated from. These checks catch the failure
 * modes that silently break a store build:
 *   1. content.js is stale (generated from an older userscript),
 *   2. the GM_* shim is missing, so the engine has no network or storage,
 *   3. the manifests disagree on version or lose a host the engine calls,
 *   4. the bootstrap bridge or the background proxy is gone.
 */

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const EXT = path.join(ROOT, 'extension');

const userSrc = fs.readFileSync(path.join(ROOT, 'movie-rating-sync.user.js'), 'utf8');
const content = fs.readFileSync(path.join(EXT, 'content.js'), 'utf8');
const bootstrap = fs.readFileSync(path.join(EXT, 'content-bootstrap.js'), 'utf8');
const background = fs.readFileSync(path.join(EXT, 'background.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(EXT, 'manifest.json'), 'utf8'));
const manifestFf = JSON.parse(fs.readFileSync(path.join(EXT, 'manifest.firefox.json'), 'utf8'));

const version = (userSrc.match(/^\/\/ @version\s+(\S+)/m) || [])[1];
assert(version, 'userscript has no @version');

const checks = [];
function ok(name, fn) {
    fn();
    checks.push(name);
}

function hostOf(url) {
    try { return new URL(url).hostname; } catch (e) { return null; }
}

// ---- 1. artifact freshness -------------------------------------------------
ok('content.js is generated from the current userscript', () => {
    assert(content.startsWith('/* Generated by tools/build-extension.js'), 'content.js is not a build artifact');
    const sample = userSrc.match(/    const YEAR_TOL = \d+;/);
    assert(sample, 'YEAR_TOL not found in userscript');
    assert(content.includes(sample[0]), 'content.js is stale — rerun node tools/build-extension.js');
    assert(content.includes('async function imdbGql('), 'engine body missing from content.js');
    assert(!content.includes('==UserScript=='), 'userscript header leaked into the extension');
});

// ---- 2. GM shim ------------------------------------------------------------
ok('content.js ships the GM_* shim', () => {
    for (const api of ['window.GM_getValue', 'window.GM_setValue', 'window.GM_deleteValue', 'window.GM_addStyle', 'window.GM = {']) {
        assert(content.includes(api), `shim is missing ${api}`);
    }
    assert(content.includes('__mrsExtHook'), 'shim does not talk to the bootstrap hook');
});

// ---- 3. manifests ----------------------------------------------------------
ok('manifests carry the userscript version', () => {
    assert.strictEqual(manifest.version, version, 'manifest.json version is stale');
    assert.strictEqual(manifestFf.version, version, 'manifest.firefox.json version is stale');
});

ok('manifests load the bootstrap before the engine', () => {
    const scripts = manifest.content_scripts[0].js;
    assert.deepStrictEqual(scripts, ['content-bootstrap.js', 'content.js']);
    assert.deepStrictEqual(manifestFf.content_scripts[0].js, scripts);
    for (const file of scripts.concat(['background.js'])) {
        assert(fs.existsSync(path.join(EXT, file)), `manifest references missing ${file}`);
    }
});

ok('manifests and background cover every @connect host', () => {
    const connects = [...userSrc.matchAll(/\/\/ @connect\s+(\S+)/g)].map(m => m[1]);
    assert(connects.length > 0, 'userscript declares no @connect hosts');
    const chromeHosts = new Set((manifest.host_permissions || []).map(hostOf).filter(Boolean));
    const firefoxHosts = new Set((manifestFf.permissions || []).map(p => hostOf(p)).filter(Boolean));
    const backgroundHosts = new Set([...background.match(/ALLOWED_HOSTS = \[([\s\S]*?)\]/)[1].matchAll(/'([^']+)'/g)].map(m => m[1]));
    for (const host of connects) {
        assert(chromeHosts.has(host), `manifest.json misses host_permission for ${host}`);
        assert(firefoxHosts.has(host), `manifest.firefox.json misses permission for ${host}`);
        assert(backgroundHosts.has(host), `background.js ALLOWED_HOSTS misses ${host}`);
    }
});

ok('firefox manifest is AMO-ready', () => {
    assert.strictEqual(manifestFf.manifest_version, 2, 'AMO build must be MV2');
    const gecko = manifestFf.browser_specific_settings?.gecko;
    assert(gecko?.id, 'gecko id is required for AMO');
    assert.deepStrictEqual(gecko.data_collection_permissions.required, ['none'],
        'AMO requires an explicit data_collection_permissions declaration');
    assert(Number(gecko.strict_min_version.split('.')[0]) >= 109,
        'strict_min_version must be >= 109 for data_collection_permissions');
});

// ---- 4. runtime pieces -----------------------------------------------------
ok('bootstrap installs the hook and the storage mirror', () => {
    assert(bootstrap.includes('window.__mrsExtHook ='), 'hook is not installed');
    assert(bootstrap.includes('chrome.storage.local'), 'settings are not persisted');
    assert(bootstrap.includes('localStorage'), 'no synchronous mirror for startup reads');
    // A download hook would break: blob URLs do not cross worlds.
    assert(!/\bdownload\s*\(/.test(bootstrap), 'bootstrap must not expose a download hook');
});

ok('background proxies requests to the allowed hosts only', () => {
    assert(background.includes("msg.type !== 'mrs:fetch'"), 'background no longer answers mrs:fetch');
    assert(background.includes("credentials: 'include'"), 'proxy must send the user cookies');
    assert(background.includes('isAllowed('), 'proxy must validate the target host');
});

ok('icons exist for every manifest size', () => {
    for (const size of ['16', '48', '128']) {
        const icon = path.join(EXT, 'icons', `icon${size}.png`);
        assert(fs.existsSync(icon), `missing icons/icon${size}.png`);
        const buf = fs.readFileSync(icon);
        assert.strictEqual(buf.readUInt32BE(16), Number(size), `icon${size}.png has the wrong width`);
        assert.strictEqual(buf.readUInt32BE(20), Number(size), `icon${size}.png has the wrong height`);
        assert(manifest.icons[size] && manifestFf.icons[size], `manifest misses icon ${size}`);
    }
});

console.log(`extension-build: ${checks.length} checks`);
for (const name of checks) console.log('  ✓', name);
console.log('ALL OK');
